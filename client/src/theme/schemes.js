export const DEFAULT_SCHEME_ID = 'ember'

/** Write a scheme's accent variables onto the document root. */
export function applyScheme(scheme) {
  const root = document.documentElement
  root.style.setProperty('--color-accent', scheme.accent)
  root.style.setProperty('--color-accent-soft', scheme.soft)
  root.style.setProperty('--color-accent-strong', scheme.strong)
  root.style.setProperty('--color-accent-deep', scheme.deep)
  root.style.setProperty('--accent-rgb', scheme.rgb)
  root.style.setProperty('--accent-contrast', scheme.contrast)
}
